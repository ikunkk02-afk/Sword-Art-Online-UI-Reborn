package be.bluexin.mcui.mixin.client;

import be.bluexin.mcui.screens.SaoScreenRouter;
import net.minecraft.client.Minecraft;
import net.minecraft.client.gui.screens.Screen;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.ModifyVariable;

@Mixin(Minecraft.class)
public abstract class MinecraftScreenRouterMixin {
    @ModifyVariable(method = {"setScreen", "forceSetScreen"}, at = @At("HEAD"), argsOnly = true)
    private Screen mcui$routeScreen(Screen screen) {
        return SaoScreenRouter.route(screen);
    }
}
